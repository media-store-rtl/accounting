    public function service(string $slug): View
    {
        $services = self::services();
        abort_unless(isset($services[$slug]), 404);

        return view('farnam-public.service', ['service' => $services[$slug], 'slug' => $slug]);
    }

    public function articles(): View
    {
        return view('farnam-public.articles.index', ['articles' => self::articles()]);
    }

    public function article(string $slug): View
    {
        $articles = self::articles();
        abort_unless(isset($articles[$slug]), 404);

        return view('farnam-public.articles.show', ['article' => $articles[$slug], 'slug' => $slug]);
    }

    public function caseStudies(): View
    {
        return view('farnam-public.case-studies');
    }

